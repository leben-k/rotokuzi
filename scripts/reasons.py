    "縁起物のモチーフ（招き猫・だるま等）を連想させるから。",
    "占いアプリの今日のラッキーナンバーに近かったから。",
    "スタッフ全員でジャンケンをして勝ち残った数字だから。",
    "この数字の並びにリズムの良さを感じたから。",
    "しばらく主役になっていない「隠れた実力派」の数字。",
